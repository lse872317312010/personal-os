import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
const root = path.dirname(fileURLToPath(import.meta.url));
const content = '"ui";\n// Generated by build.mjs; edit src/*.js.\n' +
  ['core.js', 'android.js'].map(f => fs.readFileSync(path.join(root, 'src', f), 'utf8')).join('\n');
fs.mkdirSync(path.join(root, 'dist'), {recursive:true});
fs.writeFileSync(path.join(root, 'dist', 'PersonalOS-VisualLoop.js'), content);
console.log('Built dist/PersonalOS-VisualLoop.js');
